def ensure_package(import_name: str, pip_name: str) -> None:
    try:
        importlib.import_module(import_name)
        print(f"[ok] {pip_name} is available")
    except Exception:
        print(f"[install] Installing {pip_name} ...")
        subprocess.check_call([sys.executable, "-m", "pip", "install", pip_name])
        importlib.import_module(import_name)
        print(f"[ok] {pip_name} installed")


def run_logged(cmd: list[str], cwd: Path, log_path: Path) -> bool:
    print("[cmd] " + " ".join(str(x) for x in cmd))
    with log_path.open("w", encoding="utf-8", errors="replace") as log:
        log.write("COMMAND: " + " ".join(str(x) for x in cmd) + "\n")
        log.write("CWD: " + str(cwd) + "\n" + "=" * 80 + "\n")
        proc = subprocess.run(cmd, cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")
        log.write(proc.stdout)
    if proc.returncode != 0:
        print(f"[warning] Command failed with exit code {proc.returncode}. Last log lines:")
        tail = log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-120:]
        print("\n".join(tail))
        return False
    return True


