        "spec.loader.exec_module(app)\n"
        "assert app.APP_VERSION == '1.0.9'\n"
        "engine = app.BOEngine(app.DEFAULT_CONFIG.copy())\n"
        "assert engine._auto_transfer_prior_rounds() == 4\n"
        "q = app.calc_q(20000, 0.2, None)\n"
        "assert q == 100000\n"
        "print('smoke ok')\n"
