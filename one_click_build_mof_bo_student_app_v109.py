        exe_dst = release / ("MOF_BO_Student_App.exe" if os.name == "nt" else "MOF_BO_Student_App")
        shutil.copy2(exe_src, exe_dst)
        zip_path = release / f"MOF_BO_Student_App_v109_{timestamp}_single_exe.zip"
        safe_zip_file(zip_path, [(exe_dst, exe_dst.name), (readme, readme.name)])
        send_message = f"ZIP to send to students: {zip_path}"
